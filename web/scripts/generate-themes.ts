import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

type Palette = {
  neutral: string;
  ink: string;
  primary: string;
  accent?: string;
  success: string;
  warning: string;
  error: string;
  info: string;
  diffAdd?: string;
  diffDelete?: string;
};

type ThemeVariant = {
  palette: Palette;
  overrides: Record<string, string>;
};

type Theme = {
  id: string;
  name: string;
  light: ThemeVariant;
  dark: ThemeVariant;
};

type ThemeSource = {
  _source?: string;
  _sourceCommit?: string;
  themes: Theme[];
};

const root = process.cwd();
const sourcePath = resolve(root, "src/lib/theme/opencode-themes.json");
const source = JSON.parse(await readFile(sourcePath, "utf8")) as ThemeSource;

function hexToRgb(hex: string) {
  const normalized = hex.replace("#", "");
  const full =
    normalized.length === 3
      ? normalized
          .split("")
          .map((character) => `${character}${character}`)
          .join("")
      : normalized;
  const value = Number.parseInt(full, 16);

  return {
    r: ((value >> 16) & 255) / 255,
    g: ((value >> 8) & 255) / 255,
    b: (value & 255) / 255,
  };
}

function relativeLuminance(hex: string) {
  const { r, g, b } = hexToRgb(hex);
  const linear = (channel: number) =>
    channel <= 0.03928 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;

  return 0.2126 * linear(r) + 0.7152 * linear(g) + 0.0722 * linear(b);
}

function foregroundFor(hex: string) {
  return relativeLuminance(hex) > 0.5 ? "#0a0a0a" : "#ffffff";
}

function mix(base: string, color: string, percent: number) {
  return `color-mix(in oklab, ${base}, ${color} ${percent}%)`;
}

function buildVariables(
  palette: Palette,
  overrides: Record<string, string>,
  mode: "light" | "dark",
) {
  const isDark = mode === "dark";
  const accent = palette.accent ?? palette.info ?? palette.primary;
  const diffAdd = palette.diffAdd ?? palette.success;
  const diffDelete = palette.diffDelete ?? palette.error;
  const mutedForeground =
    overrides["syntax-comment"] ??
    mix(palette.ink, palette.neutral, isDark ? 45 : 40);

  const syntax = Object.fromEntries(
    Object.entries(overrides)
      .filter(
        ([key, value]) =>
          key.startsWith("syntax-") && typeof value === "string",
      )
      .map(([key, value]) => [`--${key}`, value]),
  );

  return {
    "--background": palette.neutral,
    "--foreground": palette.ink,
    "--card": mix(palette.neutral, "#ffffff", 4),
    "--card-foreground": palette.ink,
    "--popover": mix(palette.neutral, "#ffffff", 4),
    "--popover-foreground": palette.ink,
    "--primary": palette.primary,
    "--primary-foreground": foregroundFor(palette.primary),
    "--secondary": mix(palette.neutral, palette.ink, 7),
    "--secondary-foreground": palette.ink,
    "--muted": mix(palette.neutral, palette.ink, 5),
    "--muted-foreground": mutedForeground,
    "--accent": mix(palette.neutral, palette.ink, 10),
    "--accent-foreground": palette.ink,
    "--destructive": palette.error,
    "--border": mix(palette.neutral, palette.ink, isDark ? 18 : 12),
    "--input": mix(palette.neutral, palette.ink, isDark ? 24 : 16),
    "--ring": palette.primary,
    "--success": palette.success,
    "--warning": palette.warning,
    "--info": palette.info,
    "--diff-add": diffAdd,
    "--diff-delete": diffDelete,
    "--chart-1": palette.primary,
    "--chart-2": accent,
    "--chart-3": palette.success,
    "--chart-4": palette.warning,
    "--chart-5": palette.info,
    "--sidebar": mix(palette.neutral, isDark ? "#ffffff" : palette.ink, 3),
    "--sidebar-foreground": palette.ink,
    "--sidebar-primary": palette.primary,
    "--sidebar-primary-foreground": foregroundFor(palette.primary),
    "--sidebar-accent": mix(palette.neutral, palette.ink, 10),
    "--sidebar-accent-foreground": palette.ink,
    "--sidebar-border": mix(palette.neutral, palette.ink, isDark ? 18 : 12),
    "--sidebar-ring": palette.primary,
    ...syntax,
  };
}

function block(selector: string, variables: Record<string, string>) {
  return [
    `${selector} {`,
    ...Object.entries(variables).map(
      ([property, value]) => `  ${property}: ${value};`,
    ),
    "}",
  ].join("\n");
}

const cssBlocks = source.themes.flatMap((theme) => [
  block(
    `html[data-color-theme="${theme.id}"]`,
    buildVariables(theme.light.palette, theme.light.overrides, "light"),
  ),
  "",
  block(
    `html[data-color-theme="${theme.id}"].dark`,
    buildVariables(theme.dark.palette, theme.dark.overrides, "dark"),
  ),
  "",
]);

const css = [
  "/* Generated by scripts/generate-themes.ts from opencode-themes.json. */",
  "/* Do not edit by hand. Run `npm run themes:generate` instead. */",
  source._sourceCommit
    ? `/* OpenCode source commit: ${source._sourceCommit} */`
    : null,
  "",
  ...cssBlocks,
]
  .filter((line): line is string => line !== null)
  .join("\n");

function preview(palette: Palette) {
  return {
    neutral: palette.neutral,
    ink: palette.ink,
    primary: palette.primary,
    accent: palette.accent ?? palette.info ?? palette.primary,
  };
}

const defaultPreview = {
  id: "default",
  name: "Stripe",
  light: {
    neutral: "#ffffff",
    ink: "#0d253d",
    primary: "#533afd",
    accent: "#ea2261",
  },
  dark: {
    neutral: "#0b1020",
    ink: "#f5f7fb",
    primary: "#8b7cff",
    accent: "#fb7185",
  },
} as const;

const options = [
  defaultPreview,
  ...source.themes.map((theme) => ({
    id: theme.id,
    name: theme.name,
    light: preview(theme.light.palette),
    dark: preview(theme.dark.palette),
  })),
];

const optionsFile = [
  "// Generated by scripts/generate-themes.ts from opencode-themes.json.",
  "// Do not edit by hand. Run `npm run themes:generate` instead.",
  "",
  `export const COLOR_THEME_OPTIONS = ${JSON.stringify(options, null, 2)} as const;`,
  "",
  'export type ColorThemeId = (typeof COLOR_THEME_OPTIONS)[number]["id"];',
  "",
].join("\n");

await writeFile(resolve(root, "src/styles/themes.css"), css, "utf8");
await writeFile(
  resolve(root, "src/lib/theme/theme-options.ts"),
  optionsFile,
  "utf8",
);

console.log(
  `Generated ${source.themes.length + 1} color themes (including the default).`,
);
